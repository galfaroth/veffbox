# Generates core/vb_tables.h: the constant tables the fixed-point core uses.
# The FM-1 has no FPU, so every curve that needs exp/sin/tanh is computed here, once.
#   python3 tools/gen_tables.py > core/vb_tables.h
import math

SR = 44100


def row(vals, per=12):
    out = []
    for i in range(0, len(vals), per):
        out.append("    " + ", ".join(str(v) for v in vals[i:i + per]) + ",")
    return "\n".join(out)


def main():
    print("/* SPDX-License-Identifier: GPL-3.0-only */")
    print("/* Generated by tools/gen_tables.py. Do not edit. */")
    print("#ifndef VB_TABLES_H\n#define VB_TABLES_H\n#include <stdint.h>\n")

    # one full sine cycle, Q15, 1024 points + 1 guard point for interpolation
    sin = [round(32767 * math.sin(2 * math.pi * i / 1024)) for i in range(1025)]
    print("static const int16_t VB_SIN[1025] = {\n" + row(sin) + "\n};\n")

    # tanh over x in [-4, 4], Q15 in and out, 256 steps + guard
    th = [round(32767 * math.tanh(-4 + 8 * i / 256)) for i in range(257)]
    print("static const int16_t VB_TANH[257] = {\n" + row(th) + "\n};\n")

    # per-sample exponential decay coefficients, Q30: time constant 2 ms .. 2 s over 128 steps
    dec = []
    for i in range(128):
        tau = 0.002 * (1000 ** (i / 127))
        dec.append(round((1 << 30) * math.exp(-1 / (tau * SR))))
    print("/* VB_DECAY[i]: tau = 2 ms * 1000^(i/127) */")
    print("static const int32_t VB_DECAY[128] = {\n" + row(dec, 8) + "\n};\n")

    # free-running LFO phase increment per sample for 0.05 Hz * 2^(v/14), v = 0..127
    inc = [round(0.05 * 2 ** (v / 14) * 2 ** 32 / SR) for v in range(128)]
    print("static const uint32_t VB_LFO_INC[128] = {\n" + row(inc, 8) + "\n};\n")

    # one-pole low-pass coefficient (Q15) for a cutoff of 40 Hz * 2^(v/12.7), v = 0..127 (~40 Hz .. 40 kHz)
    lp = []
    for v in range(128):
        fc = min(40 * 2 ** (v / 12.7), SR * 0.45)
        lp.append(round(32767 * (1 - math.exp(-2 * math.pi * fc / SR))))
    print("static const int16_t VB_ONEPOLE[128] = {\n" + row(lp) + "\n};\n")

    print("#endif")


if __name__ == "__main__":
    main()
